function runTypesAndDocsStep(scriptPath: string) {
    const result = spawnSync("tsx", [scriptPath], {
        cwd: ROOT_DIR,
        stdio: "inherit",
        shell: process.platform === "win32",
    });
    if (result.status !== 0) {
        throw new Error(`config sync failed: ${scriptPath}`);
    }
}

function main() {
    const runtimeChanged = syncRuntimeParams();
    const terrainChanged = syncTerrainParams();
    const climateChanged = syncClimateParams();
    const glaciologyChanged = syncGlaciologyParams();
    runTypesAndDocsStep("tools/sync/generate-config-types.ts");
    runTypesAndDocsStep("tools/sync/generate-config-docs.ts");

    const changedTotal = runtimeChanged + terrainChanged + climateChanged + glaciologyChanged;
    console.log(`config:sync completed (${changedTotal} config file(s) updated before docs/types)`);
}

main();
